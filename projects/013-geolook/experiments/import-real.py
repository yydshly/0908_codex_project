"""Import captured browser evidence through GeoLook's original parser and storage.

Mark D for provenance review: anonymous web was observed, browser incognito was not.
No answer is generated by this importer and failed platform responses are excluded.
"""
import json
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'upstream/geolook/scripts'))
import geolib as G
import sample as S
cfg=G.load_config('obsidian-real')
cfg['platforms']=['chatgpt']
G.save_config('obsidian-real',cfg)
rows=[]
for f in sorted((Path(__file__).parent/'real-samples').glob('q*.json')):
    r=json.loads(f.read_text(encoding='utf-8'))
    answer=r['answer'].removeprefix('ChatGPT 说：').strip()
    # Copy response UI labels are not answer content. Preserve raw record separately.
    for trailer in ['复制回复\n分享','登录即可获得为你量身定制的建议和推荐。\n登录\n免费注册']:
        if answer.endswith(trailer):answer=answer[:-len(trailer)].strip()
    rows.append({'date':G.today(),'ts':r['collected_at'],'platform':'chatgpt',
        'platform_name':S.label_of('chatgpt'),'market':'global','terminal':'web','sample_mode':'browser',
        'session_mode':'unverified_anonymous','session_label':'未登录网页新会话；浏览器隐私模式未确认',
        'session_note':r['session_note'],'evidence_level':'D_待复核','search_enabled':r.get('search_enabled'),
        'question_id':r['question_id'],'question':r['question'],'round':1,'ok':True,'error':None,
        'answer':answer,'citations':r['citations'],'page_url':r['page_url'],
        'brand_in_question':S.brand_in_question(r['question'],cfg),
        'analysis':S.analyze_answer(answer,cfg,r['citations']),
        'needs_review':True,'review_note':'真实网页答案，仍需复核事实及采样环境；本轮小样本仅用于展示。'})
assert rows,'No captured records'
# This research importer is repeatable; upstream itself appends imported rows.
# Retain a backup and replace only records from the exact same captured sessions.
path=G.project_dir('obsidian-real')/'samples'/f'{G.today()}.jsonl'
existing=G.read_jsonl(path)
identity=lambda r:(r.get('question_id'),r.get('platform'),r.get('round'),r.get('ts'))
incoming={identity(r) for r in rows}
if existing:
    backup=Path(__file__).parent/'real-samples/import-before-dedup.jsonl'
    if not backup.exists():G.write_jsonl(backup,existing)
    G.write_jsonl(path,[r for r in existing if identity(r) not in incoming])
m=S.store_manual_rows('obsidian-real',cfg,rows)
print(json.dumps(m,ensure_ascii=False,indent=2))
